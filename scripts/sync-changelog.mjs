import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, writeFileSync, mkdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const projectRoot = resolve(import.meta.dirname, '..')
const dataDir = join(projectRoot, 'docs', '.vitepress', 'data')
const configuredRepo = process.env.RIFFLE_REPO_PATH
const scratch = configuredRepo ? null : mkdtempSync(join(tmpdir(), 'riffle-changelog-'))
const repoDir = configuredRepo ? resolve(configuredRepo) : join(scratch, 'riffle')

function git(...args) {
  return execFileSync('git', ['-C', repoDir, ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit']
  }).trim()
}

function gitOptional(...args) {
  try {
    return execFileSync('git', ['-C', repoDir, ...args], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe']
    }).trim()
  } catch {
    return null
  }
}

function parseVersion(tag) {
  const match = tag.match(/^v(\d+)\.(\d+)\.(\d+)(?:-([a-z]+)(\d+))?$/i)
  if (!match) return { major: 0, minor: 0, patch: 0, prerelease: tag, prereleaseNumber: 0 }
  return {
    major: Number(match[1]),
    minor: Number(match[2]),
    patch: Number(match[3]),
    prerelease: match[4] ?? '',
    prereleaseNumber: Number(match[5] ?? 0)
  }
}

function compareVersions(a, b) {
  const left = parseVersion(a.tag)
  const right = parseVersion(b.tag)
  for (const key of ['major', 'minor', 'patch']) {
    if (left[key] !== right[key]) return right[key] - left[key]
  }
  if (!left.prerelease && right.prerelease) return -1
  if (left.prerelease && !right.prerelease) return 1
  return right.prereleaseNumber - left.prereleaseNumber
}

const typeMap = {
  feat: 'features',
  fix: 'fixes',
  perf: 'performance',
  refactor: 'improvements',
  docs: 'documentation',
  build: 'maintenance',
  ci: 'maintenance',
  test: 'maintenance',
  chore: 'maintenance'
}

function parseCommit(line) {
  const [hash, ...subjectParts] = line.split('|')
  let subject = subjectParts.join('|').trim()
  const prMatch = subject.match(/\s+\(#(\d+)\)$/)
  const pr = prMatch ? Number(prMatch[1]) : null
  if (prMatch) subject = subject.slice(0, prMatch.index).trim()

  const conventional = subject.match(/^([a-z]+)(?:\(([^)]+)\))?(!)?:\s*(.+)$/i)
  const rawType = conventional?.[1]?.toLowerCase()
  return {
    hash,
    subject: conventional?.[4] ?? subject,
    scope: conventional?.[2] ?? null,
    breaking: Boolean(conventional?.[3]),
    category: typeMap[rawType] ?? 'other',
    pr
  }
}

try {
  if (!configuredRepo) {
    execFileSync('git', ['clone', '--filter=blob:none', '--no-checkout', 'https://github.com/zuston/riffle.git', repoDir], {
      stdio: 'inherit'
    })
  }

  const refs = git(
    'for-each-ref',
    '--format=%(refname:short)|%(creatordate:short)|%(objectname:short)',
    'refs/tags'
  )

  const releases = refs
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const [tag, date, commit] = line.split('|')
      return {
        tag,
        date,
        commit,
        channel: tag.includes('-') ? 'pre-release' : 'stable'
      }
    })
    .sort(compareVersions)

  const tagsByCommit = new Map()
  for (const release of releases) {
    const tags = tagsByCommit.get(release.commit) ?? []
    tags.push(release)
    tagsByCommit.set(release.commit, tags)
  }

  for (const release of releases) {
    const siblingPrerelease = release.channel === 'stable'
      ? tagsByCommit.get(release.commit)?.filter((item) => item.channel === 'pre-release').sort(compareVersions)[0]
      : null

    if (siblingPrerelease) {
      release.identicalTo = siblingPrerelease.tag
      release.previousTag = siblingPrerelease.tag
      release.changes = []
      continue
    }

    const previousTag = gitOptional('describe', '--tags', '--abbrev=0', `${release.tag}^`)

    release.previousTag = previousTag
    const range = previousTag ? `${previousTag}..${release.tag}` : release.tag
    const log = git('log', '--no-merges', '--pretty=format:%h|%s', range)
    release.changes = log ? log.split('\n').map(parseCommit) : []
  }

  mkdirSync(dataDir, { recursive: true })
  const dataSource = `// Generated by scripts/sync-changelog.mjs. Do not edit by hand.
export type ChangeCategory =
  | 'features'
  | 'fixes'
  | 'performance'
  | 'improvements'
  | 'documentation'
  | 'maintenance'
  | 'other'

export type RiffleChange = {
  hash: string
  subject: string
  scope: string | null
  breaking: boolean
  category: ChangeCategory
  pr: number | null
}

export type RiffleRelease = {
  tag: string
  date: string
  commit: string
  channel: 'stable' | 'pre-release'
  previousTag: string | null
  identicalTo?: string
  changes: RiffleChange[]
}

export const releases: RiffleRelease[] = ${JSON.stringify(releases, null, 2)}
`

  writeFileSync(join(dataDir, 'changelog.ts'), dataSource)
  console.log(`Generated changelog data for ${releases.length} tags`)
} finally {
  if (scratch) rmSync(scratch, { recursive: true, force: true })
}
